-- Tipos de documento: en qué lista aparece cada uno y en qué orden (1 = el más común)
ALTER TABLE "TIPOS_DOCUMENTO" ADD COLUMN IF NOT EXISTS "USO_RESPUESTA" BOOLEAN NOT NULL DEFAULT TRUE;
ALTER TABLE "TIPOS_DOCUMENTO" ADD COLUMN IF NOT EXISTS "USO_SOLICITUD" BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE "TIPOS_DOCUMENTO" ADD COLUMN IF NOT EXISTS "ORDEN" INT NOT NULL DEFAULT 50;
ALTER TABLE "TIPOS_DOCUMENTO" ADD COLUMN IF NOT EXISTS "ORDEN_SOLICITUD" INT NOT NULL DEFAULT 50;

INSERT INTO "TIPOS_DOCUMENTO" ("NOMBRE", "PREFIJO") VALUES ('Solicitud', 'SOLICITUD')
ON CONFLICT ("NOMBRE") DO NOTHING;

UPDATE "TIPOS_DOCUMENTO" t
SET "USO_RESPUESTA" = v.r, "USO_SOLICITUD" = v.s, "ORDEN" = v.o, "ORDEN_SOLICITUD" = v.os
FROM (VALUES
    ('Informe Legal', TRUE, FALSE, 1, 50),
    ('Opinión Legal', TRUE, FALSE, 2, 50),
    ('Oficio', TRUE, TRUE, 3, 1),
    ('Memorando', TRUE, TRUE, 4, 2),
    ('Oficio Múltiple', TRUE, TRUE, 5, 5),
    ('Memorando Múltiple', TRUE, TRUE, 6, 6),
    ('Informe', TRUE, TRUE, 7, 4),
    ('Proveído', TRUE, TRUE, 8, 3),
    ('Carta', TRUE, TRUE, 9, 8),
    ('Solicitud', FALSE, TRUE, 50, 7)
) AS v (nombre, r, s, o, os)
WHERE t."NOMBRE" = v.nombre;

-- Informes: datos de la pregunta
ALTER TABLE "INFORMES" ADD COLUMN IF NOT EXISTS "ID_TIPO_SOLICITUD" INT NULL;
ALTER TABLE "INFORMES" ADD COLUMN IF NOT EXISTS "NUMERO_SOLICITUD" VARCHAR(150) NULL;
ALTER TABLE "INFORMES" ADD COLUMN IF NOT EXISTS "ID_UE_SOLICITANTE" INT NULL;
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'FK_INFORMES_TIPO_SOLICITUD') THEN
        ALTER TABLE "INFORMES" ADD CONSTRAINT "FK_INFORMES_TIPO_SOLICITUD"
            FOREIGN KEY ("ID_TIPO_SOLICITUD") REFERENCES "TIPOS_DOCUMENTO" ("ID_TIPO_DOCUMENTO");
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'FK_INFORMES_UE_SOLICITANTE') THEN
        ALTER TABLE "INFORMES" ADD CONSTRAINT "FK_INFORMES_UE_SOLICITANTE"
            FOREIGN KEY ("ID_UE_SOLICITANTE") REFERENCES "UNIDADES_EJECUTORAS" ("ID_UNIDAD_EJECUTORA");
    END IF;
END $$;
CREATE INDEX IF NOT EXISTS "IX_INFORMES_UE_SOLICITANTE" ON "INFORMES" ("ID_UE_SOLICITANTE");

-- Archivos: nueva categoría SOLICITUD (PDF de la pregunta)
ALTER TABLE "INFORME_ARCHIVOS" DROP CONSTRAINT IF EXISTS "CHK_INFORME_ARCHIVOS_CATEGORIA";
ALTER TABLE "INFORME_ARCHIVOS" ADD CONSTRAINT "CHK_INFORME_ARCHIVOS_CATEGORIA"
    CHECK ("CATEGORIA" IN ('OFICIAL', 'SOLICITUD', 'ANTECEDENTE'));
