ALTER TABLE "INFORMES" ADD COLUMN IF NOT EXISTS "VIGENCIA_CRITERIO" VARCHAR(20) NOT NULL DEFAULT 'VIGENTE';
ALTER TABLE "INFORMES" ADD COLUMN IF NOT EXISTS "ID_SUPERADO_POR" INT NULL
    CONSTRAINT "FK_INFORMES_SUPERADO_POR" REFERENCES "INFORMES" ("ID_INFORME");
ALTER TABLE "INFORMES" ADD COLUMN IF NOT EXISTS "NOTA_VIGENCIA" VARCHAR(500) NULL;
ALTER TABLE "INFORMES" DROP CONSTRAINT IF EXISTS "CHK_INFORMES_VIGENCIA";
ALTER TABLE "INFORMES" ADD CONSTRAINT "CHK_INFORMES_VIGENCIA" CHECK ("VIGENCIA_CRITERIO" IN ('VIGENTE', 'SUPERADO'));

ALTER TABLE "INFORME_ARCHIVOS" ADD COLUMN IF NOT EXISTS "CATEGORIA" VARCHAR(20) NOT NULL DEFAULT 'OFICIAL';
ALTER TABLE "INFORME_ARCHIVOS" ADD COLUMN IF NOT EXISTS "DESCRIPCION" VARCHAR(300) NULL;
ALTER TABLE "INFORME_ARCHIVOS" DROP CONSTRAINT IF EXISTS "CHK_INFORME_ARCHIVOS_CATEGORIA";
ALTER TABLE "INFORME_ARCHIVOS" ADD CONSTRAINT "CHK_INFORME_ARCHIVOS_CATEGORIA" CHECK ("CATEGORIA" IN ('OFICIAL', 'ANTECEDENTE'));
ALTER TABLE "INFORME_ARCHIVOS" DROP CONSTRAINT IF EXISTS "UQ_INFORME_ARCHIVOS_VERSION";
ALTER TABLE "INFORME_ARCHIVOS" ADD CONSTRAINT "UQ_INFORME_ARCHIVOS_VERSION" UNIQUE ("ID_INFORME", "CATEGORIA", "VERSION");

CREATE TABLE IF NOT EXISTS "NORMAS" (
    "ID_NORMA" INT GENERATED BY DEFAULT AS IDENTITY CONSTRAINT "PK_NORMAS" PRIMARY KEY,
    "DENOMINACION" VARCHAR(300) NOT NULL CONSTRAINT "UQ_NORMAS_DENOMINACION" UNIQUE,
    "TIPO" VARCHAR(50) NULL,
    "NUMERO" VARCHAR(50) NULL,
    "ACTIVO" BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS "INFORME_NORMAS" (
    "ID_INFORME_NORMA" INT GENERATED BY DEFAULT AS IDENTITY CONSTRAINT "PK_INFORME_NORMAS" PRIMARY KEY,
    "ID_INFORME" INT NOT NULL CONSTRAINT "FK_INFORME_NORMAS_INFORME" REFERENCES "INFORMES" ("ID_INFORME") ON DELETE CASCADE,
    "ID_NORMA" INT NOT NULL CONSTRAINT "FK_INFORME_NORMAS_NORMA" REFERENCES "NORMAS" ("ID_NORMA"),
    "ARTICULOS" VARCHAR(300) NULL,
    "ORDEN" INT NOT NULL DEFAULT 0,
    CONSTRAINT "UQ_INFORME_NORMAS" UNIQUE ("ID_INFORME", "ID_NORMA")
);
CREATE INDEX IF NOT EXISTS "IX_INFORME_NORMAS_NORMA" ON "INFORME_NORMAS" ("ID_NORMA");

CREATE TABLE IF NOT EXISTS "INFORME_RELACIONES" (
    "ID_RELACION" INT GENERATED BY DEFAULT AS IDENTITY CONSTRAINT "PK_INFORME_RELACIONES" PRIMARY KEY,
    "ID_INFORME" INT NOT NULL CONSTRAINT "FK_INFORME_RELACIONES_INFORME" REFERENCES "INFORMES" ("ID_INFORME"),
    "ID_INFORME_RELACIONADO" INT NOT NULL CONSTRAINT "FK_INFORME_RELACIONES_RELACIONADO" REFERENCES "INFORMES" ("ID_INFORME"),
    "TIPO" VARCHAR(20) NOT NULL DEFAULT 'RELACIONADO',
    "NOTA" VARCHAR(500) NULL,
    CONSTRAINT "UQ_INFORME_RELACIONES" UNIQUE ("ID_INFORME", "ID_INFORME_RELACIONADO"),
    CONSTRAINT "CHK_INFORME_RELACIONES_TIPO" CHECK ("TIPO" IN ('RELACIONADO', 'SUPERA', 'ACLARA')),
    CONSTRAINT "CHK_INFORME_RELACIONES_DISTINTOS" CHECK ("ID_INFORME" <> "ID_INFORME_RELACIONADO")
);
CREATE INDEX IF NOT EXISTS "IX_INFORME_RELACIONES_RELACIONADO" ON "INFORME_RELACIONES" ("ID_INFORME_RELACIONADO");

