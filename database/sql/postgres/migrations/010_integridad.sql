-- 1. Corrección de datos
-- Superado por sí mismo o por un informe anulado → recalcular: queda superado por el SUPERA vigente más reciente, o vigente
UPDATE "INFORMES" i SET "ID_SUPERADO_POR" = NULL, "VIGENCIA_CRITERIO" = 'VIGENTE'
WHERE i."ID_SUPERADO_POR" = i."ID_INFORME"
   OR EXISTS (SELECT 1 FROM "INFORMES" s WHERE s."ID_INFORME" = i."ID_SUPERADO_POR" AND s."ESTADO" = 'ANULADO');
UPDATE "INFORMES" i SET "VIGENCIA_CRITERIO" = 'SUPERADO', "ID_SUPERADO_POR" = x."ID_INFORME"
FROM (
    SELECT r."ID_INFORME_RELACIONADO" AS b, MAX(r."ID_INFORME") AS "ID_INFORME"
    FROM "INFORME_RELACIONES" r JOIN "INFORMES" s ON s."ID_INFORME" = r."ID_INFORME"
    WHERE r."TIPO" = 'SUPERA' AND s."ESTADO" = 'VIGENTE' AND s."ACTIVO"
    GROUP BY r."ID_INFORME_RELACIONADO"
) x
WHERE i."ID_INFORME" = x.b AND i."ID_SUPERADO_POR" IS NULL AND i."VIGENCIA_CRITERIO" = 'VIGENTE'
  AND x."ID_INFORME" <> i."ID_INFORME";

-- Más de un archivo principal por informe y categoría → solo la versión mayor
UPDATE "INFORME_ARCHIVOS" a SET "ES_PRINCIPAL" = FALSE
WHERE a."ES_PRINCIPAL" AND a."CATEGORIA" IN ('OFICIAL', 'SOLICITUD')
  AND a."VERSION" < (SELECT MAX(b."VERSION") FROM "INFORME_ARCHIVOS" b
                     WHERE b."ID_INFORME" = a."ID_INFORME" AND b."CATEGORIA" = a."CATEGORIA" AND b."ES_PRINCIPAL");

UPDATE "INFORMES" SET "MOTIVO_ANULACION" = 'Sin motivo registrado' WHERE "ESTADO" = 'ANULADO' AND "MOTIVO_ANULACION" IS NULL;
UPDATE "INFORMES" SET "FECHA_PUBLICACION" = "FECHA_CREACION" WHERE "PUBLICADO" AND "FECHA_PUBLICACION" IS NULL;
UPDATE "TIPOS_DOCUMENTO" SET "USO_RESPUESTA" = TRUE WHERE NOT "USO_RESPUESTA" AND NOT "USO_SOLICITUD";

-- Más de una Sede Central → queda la de menor id
UPDATE "UNIDADES_EJECUTORAS" SET "ES_SEDE_CENTRAL" = FALSE
WHERE "ES_SEDE_CENTRAL" AND "ID_UNIDAD_EJECUTORA" > (SELECT MIN("ID_UNIDAD_EJECUTORA") FROM "UNIDADES_EJECUTORAS" WHERE "ES_SEDE_CENTRAL");

-- Permisos con más de un destino → se conserva uno (usuario > rol > unidad ejecutora)
UPDATE "INFORME_PERMISOS" SET "ID_ROL" = NULL, "ID_UNIDAD_EJECUTORA" = NULL WHERE "ID_USUARIO" IS NOT NULL;
UPDATE "INFORME_PERMISOS" SET "ID_UNIDAD_EJECUTORA" = NULL WHERE "ID_ROL" IS NOT NULL;
-- Permisos repetidos (mismo informe y destino): queda el más antiguo con PUEDE_EDITAR si alguno lo tenía.
-- Es configuración de acceso, no documentación: dejar de compartir ya los elimina.
UPDATE "INFORME_PERMISOS" p SET "PUEDE_EDITAR" = TRUE
WHERE NOT p."PUEDE_EDITAR" AND EXISTS (
    SELECT 1 FROM "INFORME_PERMISOS" q WHERE q."ID_INFORME" = p."ID_INFORME" AND q."PUEDE_EDITAR"
      AND q."ID_USUARIO" IS NOT DISTINCT FROM p."ID_USUARIO" AND q."ID_ROL" IS NOT DISTINCT FROM p."ID_ROL"
      AND q."ID_UNIDAD_EJECUTORA" IS NOT DISTINCT FROM p."ID_UNIDAD_EJECUTORA");
DELETE FROM "INFORME_PERMISOS" p USING "INFORME_PERMISOS" q
WHERE p."ID_INFORME_PERMISO" > q."ID_INFORME_PERMISO" AND p."ID_INFORME" = q."ID_INFORME"
  AND p."ID_USUARIO" IS NOT DISTINCT FROM q."ID_USUARIO" AND p."ID_ROL" IS NOT DISTINCT FROM q."ID_ROL"
  AND p."ID_UNIDAD_EJECUTORA" IS NOT DISTINCT FROM q."ID_UNIDAD_EJECUTORA";

-- 2. Restricciones (DROP IF EXISTS + ADD: se puede correr más de una vez)
