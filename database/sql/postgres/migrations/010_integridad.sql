ALTER TABLE "INFORMES" DROP CONSTRAINT IF EXISTS "CHK_INFORMES_ANIO";
ALTER TABLE "INFORMES" ADD CONSTRAINT "CHK_INFORMES_ANIO" CHECK ("ANIO" BETWEEN 1990 AND 2100);
ALTER TABLE "INFORMES" DROP CONSTRAINT IF EXISTS "CHK_INFORMES_NO_SE_SUPERA";
ALTER TABLE "INFORMES" ADD CONSTRAINT "CHK_INFORMES_NO_SE_SUPERA" CHECK ("ID_SUPERADO_POR" IS NULL OR "ID_SUPERADO_POR" <> "ID_INFORME");
ALTER TABLE "INFORMES" DROP CONSTRAINT IF EXISTS "CHK_INFORMES_ANULADO";
ALTER TABLE "INFORMES" ADD CONSTRAINT "CHK_INFORMES_ANULADO" CHECK ("ESTADO" <> 'ANULADO' OR "MOTIVO_ANULACION" IS NOT NULL);
ALTER TABLE "INFORMES" DROP CONSTRAINT IF EXISTS "CHK_INFORMES_PUBLICADO";
ALTER TABLE "INFORMES" ADD CONSTRAINT "CHK_INFORMES_PUBLICADO" CHECK (NOT "PUBLICADO" OR "FECHA_PUBLICACION" IS NOT NULL);

ALTER TABLE "INFORME_ARCHIVOS" DROP CONSTRAINT IF EXISTS "CHK_INFORME_ARCHIVOS_VERSION";
ALTER TABLE "INFORME_ARCHIVOS" ADD CONSTRAINT "CHK_INFORME_ARCHIVOS_VERSION" CHECK ("VERSION" > 0);
ALTER TABLE "INFORME_ARCHIVOS" DROP CONSTRAINT IF EXISTS "CHK_INFORME_ARCHIVOS_TAMANIO";
ALTER TABLE "INFORME_ARCHIVOS" ADD CONSTRAINT "CHK_INFORME_ARCHIVOS_TAMANIO" CHECK ("TAMANIO" > 0);

ALTER TABLE "TIPOS_DOCUMENTO" DROP CONSTRAINT IF EXISTS "CHK_TIPOS_DOCUMENTO_USO";
ALTER TABLE "TIPOS_DOCUMENTO" ADD CONSTRAINT "CHK_TIPOS_DOCUMENTO_USO" CHECK ("USO_RESPUESTA" OR "USO_SOLICITUD");
ALTER TABLE "TIPOS_DOCUMENTO" DROP CONSTRAINT IF EXISTS "CHK_TIPOS_DOCUMENTO_ORDEN";
ALTER TABLE "TIPOS_DOCUMENTO" ADD CONSTRAINT "CHK_TIPOS_DOCUMENTO_ORDEN" CHECK ("ORDEN" >= 0 AND "ORDEN_SOLICITUD" >= 0);

ALTER TABLE "INFORME_PERMISOS" DROP CONSTRAINT IF EXISTS "CHK_INFORME_PERMISOS_DESTINO";
ALTER TABLE "INFORME_PERMISOS" ADD CONSTRAINT "CHK_INFORME_PERMISOS_DESTINO"
    CHECK (num_nonnulls("ID_USUARIO", "ID_ROL", "ID_UNIDAD_EJECUTORA") = 1);

-- Sin borrado en cascada: nada se borra (normas del AGN); un DELETE accidental debe fallar
