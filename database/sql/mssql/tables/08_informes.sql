-- ============================================
-- INFORMES: informes legales registrados en el repositorio
-- Numeración correlativa por tipo y año (NUMERO + ANIO únicos por tipo).
-- ESTADO: VIGENTE o ANULADO (se muestra "No vigente"). Eliminar borra el informe y lo suyo.
-- Documento de origen (la "Referencia" del informe): ID_TIPO_SOLICITUD + NUMERO_SOLICITUD + FECHA_SOLICITUD
-- (p. ej. Oficio N° 120-2026-GRM/UE-ILO) y su procedencia (ID_UE_SOLICITANTE + ID_AREA opcional, de esa UE); su PDF va en
-- INFORME_ARCHIVOS (CATEGORIA SOLICITUD). EMITIDO_DE_OFICIO: la ORAJ lo emitió por iniciativa propia, sin origen.
-- CONTROVERSIA / ANTECEDENTES / CRITERIO: sistematización (la justificación de la controversia).
-- PUBLICADO: la ORAJ lo pone a disposición de las asesorías de las unidades ejecutoras.
-- TEXTO_DOCUMENTO: texto del PDF oficial (TEXTO_EXTRAIDO = false si es escaneado).
-- TEXTO_BUSQUEDA lo arma lib/handlers/informes/indice.js (búsqueda libre con un LIKE).
-- ============================================
IF OBJECT_ID('dbo.INFORMES', 'U') IS NULL
BEGIN
    CREATE TABLE "INFORMES" (
        "ID_INFORME" INT IDENTITY(1,1) CONSTRAINT "PK_INFORMES" PRIMARY KEY,
        "ID_TIPO_DOCUMENTO" INT NOT NULL CONSTRAINT "FK_INFORMES_TIPO" REFERENCES "TIPOS_DOCUMENTO" ("ID_TIPO_DOCUMENTO"),
        "NUMERO" INT NOT NULL,
        "ANIO" INT NOT NULL,
        "CODIGO" NVARCHAR(150) NOT NULL,
        "ASUNTO" NVARCHAR(500) NOT NULL,
        "RESUMEN" NVARCHAR(3000) NULL,
        "EXPEDIENTE" NVARCHAR(100) NULL,
        "REFERENCIA" NVARCHAR(500) NULL,
        "ID_TIPO_SOLICITUD" INT NULL CONSTRAINT "FK_INFORMES_TIPO_SOLICITUD" REFERENCES "TIPOS_DOCUMENTO" ("ID_TIPO_DOCUMENTO"),
        "NUMERO_SOLICITUD" NVARCHAR(150) NULL,
        "FECHA_SOLICITUD" DATE NULL,
        "EMITIDO_DE_OFICIO" BIT NOT NULL CONSTRAINT "DF_INFORMES_DE_OFICIO" DEFAULT 0,
        "NOMBRE_ADMINISTRADO" NVARCHAR(300) NULL,
        "ID_UE_SOLICITANTE" INT NULL CONSTRAINT "FK_INFORMES_UE_SOLICITANTE" REFERENCES "UNIDADES_EJECUTORAS" ("ID_UNIDAD_EJECUTORA"),
        "ID_AREA" INT NULL CONSTRAINT "FK_INFORMES_AREA" REFERENCES "AREAS" ("ID_AREA"),
        "ID_MATERIA" INT NULL CONSTRAINT "FK_INFORMES_MATERIA" REFERENCES "MATERIAS" ("ID_MATERIA"),
        "FECHA_EMISION" DATE NOT NULL,
        "CONTROVERSIA" NVARCHAR(MAX) NULL,
        "ANTECEDENTES" NVARCHAR(MAX) NULL,
        "CRITERIO" NVARCHAR(2000) NULL,
        "CONCLUSION" NVARCHAR(MAX) NULL,
        "PALABRAS_CLAVE" NVARCHAR(500) NULL,
        "ESTADO" NVARCHAR(20) NOT NULL CONSTRAINT "DF_INFORMES_ESTADO" DEFAULT 'VIGENTE',
        "MOTIVO_ANULACION" NVARCHAR(500) NULL,
        "PUBLICADO" BIT NOT NULL CONSTRAINT "DF_INFORMES_PUBLICADO" DEFAULT 0,
        "FECHA_PUBLICACION" DATETIMEOFFSET NULL,
        "ID_USUARIO_PUBLICA" INT NULL CONSTRAINT "FK_INFORMES_USUARIO_PUBLICA" REFERENCES "USUARIOS" ("ID_USUARIO"),
        "TEXTO_DOCUMENTO" NVARCHAR(MAX) NULL,
        "TEXTO_EXTRAIDO" BIT NULL,
        "TEXTO_BUSQUEDA" NVARCHAR(MAX) NULL,
        "ID_USUARIO_REGISTRO" INT NOT NULL CONSTRAINT "FK_INFORMES_USUARIO_REGISTRO" REFERENCES "USUARIOS" ("ID_USUARIO"),
        "FECHA_CREACION" DATETIMEOFFSET NOT NULL CONSTRAINT "DF_INFORMES_FECHA_CREACION" DEFAULT SYSDATETIMEOFFSET(),
        "FECHA_MODIFICACION" DATETIMEOFFSET NULL,
        "ACTIVO" BIT NOT NULL CONSTRAINT "DF_INFORMES_ACTIVO" DEFAULT 1,
        CONSTRAINT "UQ_INFORMES_NUMERO" UNIQUE ("ID_TIPO_DOCUMENTO", "ANIO", "NUMERO"),
        CONSTRAINT "CHK_INFORMES_ESTADO" CHECK ("ESTADO" IN ('VIGENTE', 'ANULADO')),
        CONSTRAINT "CHK_INFORMES_NUMERO" CHECK ("NUMERO" > 0),
        CONSTRAINT "CHK_INFORMES_ANIO" CHECK ("ANIO" BETWEEN 1990 AND 2100),
        CONSTRAINT "CHK_INFORMES_AREA_CON_UE" CHECK ("ID_AREA" IS NULL OR "ID_UE_SOLICITANTE" IS NOT NULL),
        -- Anulado (no vigente) lleva motivo; publicado lleva fecha
        CONSTRAINT "CHK_INFORMES_ANULADO" CHECK ("ESTADO" <> 'ANULADO' OR "MOTIVO_ANULACION" IS NOT NULL),
        CONSTRAINT "CHK_INFORMES_PUBLICADO" CHECK ("PUBLICADO" = 0 OR "FECHA_PUBLICACION" IS NOT NULL)
    );
    CREATE INDEX "IX_INFORMES_ANIO" ON "INFORMES" ("ANIO", "NUMERO");
    CREATE INDEX "IX_INFORMES_MATERIA" ON "INFORMES" ("ID_MATERIA");
    CREATE INDEX "IX_INFORMES_AREA" ON "INFORMES" ("ID_AREA");
    CREATE INDEX "IX_INFORMES_UE_SOLICITANTE" ON "INFORMES" ("ID_UE_SOLICITANTE");
    CREATE INDEX "IX_INFORMES_TIPO_SOLICITUD" ON "INFORMES" ("ID_TIPO_SOLICITUD");
END
GO
