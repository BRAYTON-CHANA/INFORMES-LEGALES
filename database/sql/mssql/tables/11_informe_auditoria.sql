-- ACCION: CREAR, EDITAR, SUBIR_ARCHIVO, DESCARGAR, ANULAR
-- ============================================
IF OBJECT_ID('dbo.INFORME_AUDITORIA', 'U') IS NULL
BEGIN
    CREATE TABLE "INFORME_AUDITORIA" (
        "ID_AUDITORIA" INT IDENTITY(1,1) CONSTRAINT "PK_INFORME_AUDITORIA" PRIMARY KEY,
        "ID_INFORME" INT NOT NULL CONSTRAINT "FK_INFORME_AUDITORIA_INFORME" REFERENCES "INFORMES" ("ID_INFORME"),
        "ID_USUARIO" INT NULL CONSTRAINT "FK_INFORME_AUDITORIA_USUARIO" REFERENCES "USUARIOS" ("ID_USUARIO"),
        "ACCION" NVARCHAR(30) NOT NULL,
        "DETALLE" NVARCHAR(1000) NULL,
        "IP" NVARCHAR(64) NULL,
        "FECHA" DATETIMEOFFSET NOT NULL CONSTRAINT "DF_INFORME_AUDITORIA_FECHA" DEFAULT SYSDATETIMEOFFSET()
    );
    CREATE INDEX "IX_INFORME_AUDITORIA_INFORME" ON "INFORME_AUDITORIA" ("ID_INFORME", "FECHA");
END
GO
