-- ============================================
-- USUARIOS: usuarios del sistema (login con DNI + clave bcrypt; EMAIL solo de contacto)
-- INTENTOS_FALLIDOS / BLOQUEADO_HASTA: bloqueo temporal tras varios intentos fallidos
-- ============================================
IF OBJECT_ID('dbo.USUARIOS', 'U') IS NULL
BEGIN
    CREATE TABLE "USUARIOS" (
        "ID_USUARIO" INT IDENTITY(1,1) CONSTRAINT "PK_USUARIOS" PRIMARY KEY,
        "NOMBRES" NVARCHAR(100) NOT NULL,
        "APELLIDOS" NVARCHAR(150) NULL,
        "EMAIL" NVARCHAR(150) NULL,
        "DNI" CHAR(8) NOT NULL CONSTRAINT "UQ_USUARIOS_DNI" UNIQUE
            CONSTRAINT "CHK_USUARIOS_DNI" CHECK ("DNI" LIKE '[0-9][0-9][0-9][0-9][0-9][0-9][0-9][0-9]'),
        "PASSWORD_HASH" NVARCHAR(255) NULL,
        "REQUIERE_CAMBIO_PASSWORD" BIT NOT NULL CONSTRAINT "DF_USUARIOS_CAMBIO_PASSWORD" DEFAULT 1,
        "INTENTOS_FALLIDOS" INT NOT NULL CONSTRAINT "DF_USUARIOS_INTENTOS" DEFAULT 0,
        "BLOQUEADO_HASTA" DATETIMEOFFSET NULL,
        "ACTIVO" BIT NOT NULL CONSTRAINT "DF_USUARIOS_ACTIVO" DEFAULT 1,
        "FECHA_CREACION" DATETIMEOFFSET NOT NULL CONSTRAINT "DF_USUARIOS_FECHA_CREACION" DEFAULT SYSDATETIMEOFFSET(),
        "FECHA_EDICION" DATETIMEOFFSET NULL
    );
    CREATE UNIQUE INDEX "UX_USUARIOS_EMAIL" ON "USUARIOS" ("EMAIL") WHERE "EMAIL" IS NOT NULL;
END
GO
