-- ============================================
-- TIPOS_DOCUMENTO: tipos de documento de la pregunta (Oficio, Memorando...) y de la
-- respuesta de la ORAJ (Informe Legal, Opinión Legal, Oficio...).
-- USO_RESPUESTA / USO_SOLICITUD: en qué lista aparece; ORDEN / ORDEN_SOLICITUD: posición
-- en cada lista (1 = primero, el más común).
-- PREFIJO arma el código: "<PREFIJO> N° 001-2026-<SIGLA_ORAJ>"
-- ============================================
IF OBJECT_ID('dbo.TIPOS_DOCUMENTO', 'U') IS NULL
BEGIN
    CREATE TABLE "TIPOS_DOCUMENTO" (
        "ID_TIPO_DOCUMENTO" INT IDENTITY(1,1) CONSTRAINT "PK_TIPOS_DOCUMENTO" PRIMARY KEY,
        "NOMBRE" NVARCHAR(100) NOT NULL CONSTRAINT "UQ_TIPOS_DOCUMENTO_NOMBRE" UNIQUE,
        "PREFIJO" NVARCHAR(50) NOT NULL,
        "USO_RESPUESTA" BIT NOT NULL CONSTRAINT "DF_TIPOS_DOCUMENTO_USO_RESPUESTA" DEFAULT 1,
        "USO_SOLICITUD" BIT NOT NULL CONSTRAINT "DF_TIPOS_DOCUMENTO_USO_SOLICITUD" DEFAULT 0,
        "ORDEN" INT NOT NULL CONSTRAINT "DF_TIPOS_DOCUMENTO_ORDEN" DEFAULT 50,
        "ORDEN_SOLICITUD" INT NOT NULL CONSTRAINT "DF_TIPOS_DOCUMENTO_ORDEN_SOLICITUD" DEFAULT 50,
        "ACTIVO" BIT NOT NULL CONSTRAINT "DF_TIPOS_DOCUMENTO_ACTIVO" DEFAULT 1,
        CONSTRAINT "CHK_TIPOS_DOCUMENTO_USO" CHECK ("USO_RESPUESTA" = 1 OR "USO_SOLICITUD" = 1),
        CONSTRAINT "CHK_TIPOS_DOCUMENTO_ORDEN" CHECK ("ORDEN" >= 0 AND "ORDEN_SOLICITUD" >= 0)
    );
END
GO
