-- ============================================
-- USUARIO_ROL: roles de cada usuario
-- ============================================
IF OBJECT_ID('dbo.USUARIO_ROL', 'U') IS NULL
BEGIN
    CREATE TABLE "USUARIO_ROL" (
        "ID_USUARIO_ROL" INT IDENTITY(1,1) CONSTRAINT "PK_USUARIO_ROL" PRIMARY KEY,
        "ID_USUARIO" INT NOT NULL CONSTRAINT "FK_USUARIO_ROL_USUARIO" REFERENCES "USUARIOS" ("ID_USUARIO") ON DELETE CASCADE,
        "ID_ROL" INT NOT NULL CONSTRAINT "FK_USUARIO_ROL_ROL" REFERENCES "ROLES" ("ID_ROL") ON DELETE CASCADE,
        "ASIGNADO_POR" INT NULL CONSTRAINT "FK_USUARIO_ROL_ASIGNADOR" REFERENCES "USUARIOS" ("ID_USUARIO"),
        "FECHA_ASIGNACION" DATETIMEOFFSET NOT NULL CONSTRAINT "DF_USUARIO_ROL_FECHA" DEFAULT SYSDATETIMEOFFSET(),
        CONSTRAINT "UQ_USUARIO_ROL" UNIQUE ("ID_USUARIO", "ID_ROL")
    );
    CREATE INDEX "IX_USUARIO_ROL_ROL" ON "USUARIO_ROL" ("ID_ROL");
END
GO
