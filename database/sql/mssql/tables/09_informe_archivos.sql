-- ============================================
-- INFORME_ARCHIVOS: los dos PDF de cada informe. El binario va en Supabase Storage (RUTA_ARCHIVO)
-- o, sin Storage configurado, en CONTENIDO (lib/storage/archivos.js).
-- CATEGORIA: OFICIAL (el informe firmado) o SOLICITUD (el documento de origen con todos
-- sus anexos en un solo PDF). Cada subida es una versión nueva; HASH_SHA256 para integridad.
-- ============================================
IF OBJECT_ID('dbo.INFORME_ARCHIVOS', 'U') IS NULL
BEGIN
    CREATE TABLE "INFORME_ARCHIVOS" (
        "ID_ARCHIVO" INT IDENTITY(1,1) CONSTRAINT "PK_INFORME_ARCHIVOS" PRIMARY KEY,
        "ID_INFORME" INT NOT NULL CONSTRAINT "FK_INFORME_ARCHIVOS_INFORME" REFERENCES "INFORMES" ("ID_INFORME"),
        "CATEGORIA" NVARCHAR(20) NOT NULL CONSTRAINT "DF_INFORME_ARCHIVOS_CATEGORIA" DEFAULT 'OFICIAL',
        "NOMBRE_ORIGINAL" NVARCHAR(255) NOT NULL,
        "TIPO_MIME" NVARCHAR(100) NOT NULL,
        "TAMANIO" INT NOT NULL,
        "HASH_SHA256" CHAR(64) NOT NULL,
        "CONTENIDO" VARBINARY(MAX) NULL,
        "RUTA_ARCHIVO" NVARCHAR(500) NULL,
        "VERSION" INT NOT NULL,
        "ES_PRINCIPAL" BIT NOT NULL CONSTRAINT "DF_INFORME_ARCHIVOS_PRINCIPAL" DEFAULT 0,
        "ID_USUARIO" INT NOT NULL CONSTRAINT "FK_INFORME_ARCHIVOS_USUARIO" REFERENCES "USUARIOS" ("ID_USUARIO"),
        "FECHA_SUBIDA" DATETIMEOFFSET NOT NULL CONSTRAINT "DF_INFORME_ARCHIVOS_FECHA" DEFAULT SYSDATETIMEOFFSET(),
        "ACTIVO" BIT NOT NULL CONSTRAINT "DF_INFORME_ARCHIVOS_ACTIVO" DEFAULT 1,
        CONSTRAINT "UQ_INFORME_ARCHIVOS_VERSION" UNIQUE ("ID_INFORME", "CATEGORIA", "VERSION"),
        CONSTRAINT "CHK_INFORME_ARCHIVOS_CATEGORIA" CHECK ("CATEGORIA" IN ('OFICIAL', 'SOLICITUD')),
        CONSTRAINT "CHK_INFORME_ARCHIVOS_VERSION" CHECK ("VERSION" > 0),
        CONSTRAINT "CHK_INFORME_ARCHIVOS_TAMANIO" CHECK ("TAMANIO" > 0),
        CONSTRAINT "CHK_INFORME_ARCHIVOS_ORIGEN" CHECK ("CONTENIDO" IS NOT NULL OR "RUTA_ARCHIVO" IS NOT NULL)
    );
    -- Un solo documento principal (versión vigente) por informe y categoría
    CREATE UNIQUE INDEX "UX_INFORME_ARCHIVOS_PRINCIPAL" ON "INFORME_ARCHIVOS" ("ID_INFORME", "CATEGORIA")
        WHERE "ES_PRINCIPAL" = 1 AND "CATEGORIA" IN ('OFICIAL', 'SOLICITUD');
END
GO
