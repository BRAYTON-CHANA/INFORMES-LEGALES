-- ============================================
-- 001: unidades ejecutoras, DNI y bloqueo por intentos fallidos en USUARIOS,
-- rol asesor_ejecutora (mismo cambio que tables/00_*, 01_usuarios y seeds/)
-- ============================================
IF OBJECT_ID('dbo.UNIDADES_EJECUTORAS', 'U') IS NULL
BEGIN
    CREATE TABLE "UNIDADES_EJECUTORAS" (
        "ID_UNIDAD_EJECUTORA" INT IDENTITY(1,1) CONSTRAINT "PK_UNIDADES_EJECUTORAS" PRIMARY KEY,
        "CODIGO" NVARCHAR(10) NULL,
        "NOMBRE" NVARCHAR(200) NOT NULL CONSTRAINT "UQ_UNIDADES_EJECUTORAS_NOMBRE" UNIQUE,
        "SIGLA" NVARCHAR(30) NULL,
        "ES_SEDE_CENTRAL" BIT NOT NULL CONSTRAINT "DF_UNIDADES_EJECUTORAS_SEDE" DEFAULT 0,
        "ACTIVO" BIT NOT NULL CONSTRAINT "DF_UNIDADES_EJECUTORAS_ACTIVO" DEFAULT 1
    );
END
GO

IF COL_LENGTH('dbo.USUARIOS', 'DNI') IS NULL
    ALTER TABLE "USUARIOS" ADD "DNI" CHAR(8) NULL;
IF COL_LENGTH('dbo.USUARIOS', 'ID_UNIDAD_EJECUTORA') IS NULL
    ALTER TABLE "USUARIOS" ADD "ID_UNIDAD_EJECUTORA" INT NULL
        CONSTRAINT "FK_USUARIOS_UNIDAD_EJECUTORA" REFERENCES "UNIDADES_EJECUTORAS" ("ID_UNIDAD_EJECUTORA");
IF COL_LENGTH('dbo.USUARIOS', 'INTENTOS_FALLIDOS') IS NULL
    ALTER TABLE "USUARIOS" ADD "INTENTOS_FALLIDOS" INT NOT NULL CONSTRAINT "DF_USUARIOS_INTENTOS" DEFAULT 0;
IF COL_LENGTH('dbo.USUARIOS', 'BLOQUEADO_HASTA') IS NULL
    ALTER TABLE "USUARIOS" ADD "BLOQUEADO_HASTA" DATETIMEOFFSET NULL;
GO

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'UX_USUARIOS_DNI')
    CREATE UNIQUE INDEX "UX_USUARIOS_DNI" ON "USUARIOS" ("DNI") WHERE "DNI" IS NOT NULL;
GO

IF NOT EXISTS (SELECT 1 FROM "UNIDADES_EJECUTORAS" WHERE "ES_SEDE_CENTRAL" = 1)
    INSERT INTO "UNIDADES_EJECUTORAS" ("NOMBRE", "SIGLA", "ES_SEDE_CENTRAL")
    VALUES (N'Sede Central', N'SEDE', 1);

IF NOT EXISTS (SELECT 1 FROM "ROLES" WHERE "NOMBRE_ROL" = 'asesor_ejecutora')
    INSERT INTO "ROLES" ("NOMBRE_ROL", "DESCRIPCION", "NIVEL_ACCESO", "ES_SISTEMA")
    VALUES ('asesor_ejecutora', 'Asesor legal de unidad ejecutora: consulta los informes publicados', 1, 0);
GO
