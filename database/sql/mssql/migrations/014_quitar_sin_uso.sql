IF EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'IX_INFORMES_SUPERADO_POR' AND object_id = OBJECT_ID('dbo.INFORMES'))
    DROP INDEX "IX_INFORMES_SUPERADO_POR" ON "INFORMES";
IF EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'IX_INFORMES_ABOGADO' AND object_id = OBJECT_ID('dbo.INFORMES'))
    DROP INDEX "IX_INFORMES_ABOGADO" ON "INFORMES";
GO

-- Defaults y FK de esas columnas (por si alguno quedó con nombre generado)
DECLARE @n SYSNAME, @s NVARCHAR(400);
WHILE 1 = 1
BEGIN
    SET @n = NULL;
    SELECT TOP 1 @n = k.name FROM (
        SELECT d.name, d.parent_column_id AS col FROM sys.default_constraints d WHERE d.parent_object_id = OBJECT_ID('dbo.INFORMES')
        UNION ALL
        SELECT f.name, fc.parent_column_id FROM sys.foreign_keys f
        JOIN sys.foreign_key_columns fc ON fc.constraint_object_id = f.object_id
        WHERE f.parent_object_id = OBJECT_ID('dbo.INFORMES')
    ) k
    JOIN sys.columns c ON c.object_id = OBJECT_ID('dbo.INFORMES') AND c.column_id = k.col
    WHERE c.name IN ('VIGENCIA_CRITERIO', 'ID_SUPERADO_POR', 'NOTA_VIGENCIA', 'ID_ABOGADO', 'CLASIFICACION');
    IF @n IS NULL BREAK;
    SET @s = N'ALTER TABLE "INFORMES" DROP CONSTRAINT ' + QUOTENAME(@n);
    EXEC sp_executesql @s;
END
GO

IF COL_LENGTH('dbo.INFORMES', 'VIGENCIA_CRITERIO') IS NOT NULL ALTER TABLE "INFORMES" DROP COLUMN "VIGENCIA_CRITERIO";
IF COL_LENGTH('dbo.INFORMES', 'ID_SUPERADO_POR') IS NOT NULL ALTER TABLE "INFORMES" DROP COLUMN "ID_SUPERADO_POR";
IF COL_LENGTH('dbo.INFORMES', 'NOTA_VIGENCIA') IS NOT NULL ALTER TABLE "INFORMES" DROP COLUMN "NOTA_VIGENCIA";
IF COL_LENGTH('dbo.INFORMES', 'ID_ABOGADO') IS NOT NULL ALTER TABLE "INFORMES" DROP COLUMN "ID_ABOGADO";
IF COL_LENGTH('dbo.INFORMES', 'CLASIFICACION') IS NOT NULL ALTER TABLE "INFORMES" DROP COLUMN "CLASIFICACION";
GO
