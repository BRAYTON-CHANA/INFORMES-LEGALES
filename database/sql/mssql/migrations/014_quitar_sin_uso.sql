IF OBJECT_ID('dbo.INFORME_RELACIONES', 'U') IS NOT NULL DROP TABLE "INFORME_RELACIONES";
IF OBJECT_ID('dbo.INFORME_PERMISOS', 'U') IS NOT NULL DROP TABLE "INFORME_PERMISOS";
