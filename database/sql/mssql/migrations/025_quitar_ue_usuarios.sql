-- 025: las cuentas son solo de la ORAJ (repositorio público, 024): la unidad ejecutora del
-- usuario ya no se usa. Se quita de USUARIOS (y de VW_USUARIOS) y de INFORME_BUSQUEDAS, donde
-- se copiaba la del usuario. Mismo cambio que tables/ y views/.
-- ============================================
CREATE OR ALTER VIEW "VW_USUARIOS" AS
SELECT u."ID_USUARIO", u."DNI", u."NOMBRES", u."APELLIDOS", u."EMAIL",
       u."REQUIERE_CAMBIO_PASSWORD", u."INTENTOS_FALLIDOS", u."BLOQUEADO_HASTA", u."ACTIVO",
       u."FECHA_CREACION", u."FECHA_EDICION"
FROM "USUARIOS" u;
GO

IF OBJECT_ID('FK_USUARIOS_UNIDAD_EJECUTORA', 'F') IS NOT NULL
    ALTER TABLE "USUARIOS" DROP CONSTRAINT "FK_USUARIOS_UNIDAD_EJECUTORA";
IF COL_LENGTH('dbo.USUARIOS', 'ID_UNIDAD_EJECUTORA') IS NOT NULL
    ALTER TABLE "USUARIOS" DROP COLUMN "ID_UNIDAD_EJECUTORA";

IF OBJECT_ID('FK_INFORME_BUSQUEDAS_UE', 'F') IS NOT NULL
    ALTER TABLE "INFORME_BUSQUEDAS" DROP CONSTRAINT "FK_INFORME_BUSQUEDAS_UE";
IF COL_LENGTH('dbo.INFORME_BUSQUEDAS', 'ID_UNIDAD_EJECUTORA') IS NOT NULL
    ALTER TABLE "INFORME_BUSQUEDAS" DROP COLUMN "ID_UNIDAD_EJECUTORA";
GO
