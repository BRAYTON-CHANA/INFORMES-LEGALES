-- 003: sistematización (controversia, antecedentes, criterio y su vigencia),
-- normativa asociada, relaciones entre informes y categoría de archivos
-- (mismo cambio que tables/08, 09, 12-14 y seeds/03_normas)
-- ============================================
IF COL_LENGTH('dbo.INFORMES', 'CONTROVERSIA') IS NULL
    ALTER TABLE "INFORMES" ADD "CONTROVERSIA" NVARCHAR(MAX) NULL;
IF COL_LENGTH('dbo.INFORMES', 'ANTECEDENTES') IS NULL
    ALTER TABLE "INFORMES" ADD "ANTECEDENTES" NVARCHAR(MAX) NULL;
IF COL_LENGTH('dbo.INFORMES', 'CRITERIO') IS NULL
    ALTER TABLE "INFORMES" ADD "CRITERIO" NVARCHAR(2000) NULL;
IF COL_LENGTH('dbo.INFORMES', 'VIGENCIA_CRITERIO') IS NULL
    ALTER TABLE "INFORMES" ADD "VIGENCIA_CRITERIO" NVARCHAR(20) NOT NULL CONSTRAINT "DF_INFORMES_VIGENCIA" DEFAULT 'VIGENTE';
IF COL_LENGTH('dbo.INFORMES', 'ID_SUPERADO_POR') IS NULL
    ALTER TABLE "INFORMES" ADD "ID_SUPERADO_POR" INT NULL
        CONSTRAINT "FK_INFORMES_SUPERADO_POR" REFERENCES "INFORMES" ("ID_INFORME");
IF COL_LENGTH('dbo.INFORMES', 'NOTA_VIGENCIA') IS NULL
    ALTER TABLE "INFORMES" ADD "NOTA_VIGENCIA" NVARCHAR(500) NULL;

IF COL_LENGTH('dbo.INFORME_ARCHIVOS', 'CATEGORIA') IS NULL
    ALTER TABLE "INFORME_ARCHIVOS" ADD "CATEGORIA" NVARCHAR(20) NOT NULL CONSTRAINT "DF_INFORME_ARCHIVOS_CATEGORIA" DEFAULT 'OFICIAL';
IF COL_LENGTH('dbo.INFORME_ARCHIVOS', 'DESCRIPCION') IS NULL
    ALTER TABLE "INFORME_ARCHIVOS" ADD "DESCRIPCION" NVARCHAR(300) NULL;
GO

IF NOT EXISTS (SELECT 1 FROM sys.check_constraints WHERE name = 'CHK_INFORMES_VIGENCIA')
    ALTER TABLE "INFORMES" ADD CONSTRAINT "CHK_INFORMES_VIGENCIA" CHECK ("VIGENCIA_CRITERIO" IN ('VIGENTE', 'SUPERADO'));
IF NOT EXISTS (SELECT 1 FROM sys.check_constraints WHERE name = 'CHK_INFORME_ARCHIVOS_CATEGORIA')
    ALTER TABLE "INFORME_ARCHIVOS" ADD CONSTRAINT "CHK_INFORME_ARCHIVOS_CATEGORIA" CHECK ("CATEGORIA" IN ('OFICIAL', 'ANTECEDENTE'));
GO

-- La versión pasa a contarse por categoría
IF EXISTS (
    SELECT 1 FROM sys.key_constraints kc
    WHERE kc.name = 'UQ_INFORME_ARCHIVOS_VERSION'
      AND NOT EXISTS (
        SELECT 1 FROM sys.index_columns ic JOIN sys.columns c ON c.object_id = ic.object_id AND c.column_id = ic.column_id
        WHERE ic.object_id = kc.parent_object_id AND ic.index_id = kc.unique_index_id AND c.name = 'CATEGORIA')
)
    ALTER TABLE "INFORME_ARCHIVOS" DROP CONSTRAINT "UQ_INFORME_ARCHIVOS_VERSION";
GO
IF NOT EXISTS (SELECT 1 FROM sys.key_constraints WHERE name = 'UQ_INFORME_ARCHIVOS_VERSION')
    ALTER TABLE "INFORME_ARCHIVOS" ADD CONSTRAINT "UQ_INFORME_ARCHIVOS_VERSION" UNIQUE ("ID_INFORME", "CATEGORIA", "VERSION");
GO

IF OBJECT_ID('dbo.NORMAS', 'U') IS NULL
BEGIN
    CREATE TABLE "NORMAS" (
        "ID_NORMA" INT IDENTITY(1,1) CONSTRAINT "PK_NORMAS" PRIMARY KEY,
        "DENOMINACION" NVARCHAR(300) NOT NULL CONSTRAINT "UQ_NORMAS_DENOMINACION" UNIQUE,
        "TIPO" NVARCHAR(50) NULL,
        "NUMERO" NVARCHAR(50) NULL,
        "ACTIVO" BIT NOT NULL CONSTRAINT "DF_NORMAS_ACTIVO" DEFAULT 1
    );
END
GO

IF OBJECT_ID('dbo.INFORME_NORMAS', 'U') IS NULL
BEGIN
    CREATE TABLE "INFORME_NORMAS" (
        "ID_INFORME_NORMA" INT IDENTITY(1,1) CONSTRAINT "PK_INFORME_NORMAS" PRIMARY KEY,
        "ID_INFORME" INT NOT NULL CONSTRAINT "FK_INFORME_NORMAS_INFORME" REFERENCES "INFORMES" ("ID_INFORME") ON DELETE CASCADE,
        "ID_NORMA" INT NOT NULL CONSTRAINT "FK_INFORME_NORMAS_NORMA" REFERENCES "NORMAS" ("ID_NORMA"),
        "ARTICULOS" NVARCHAR(300) NULL,
        "ORDEN" INT NOT NULL CONSTRAINT "DF_INFORME_NORMAS_ORDEN" DEFAULT 0,
        CONSTRAINT "UQ_INFORME_NORMAS" UNIQUE ("ID_INFORME", "ID_NORMA")
    );
    CREATE INDEX "IX_INFORME_NORMAS_NORMA" ON "INFORME_NORMAS" ("ID_NORMA");
END
GO

IF OBJECT_ID('dbo.INFORME_RELACIONES', 'U') IS NULL
BEGIN
    CREATE TABLE "INFORME_RELACIONES" (
        "ID_RELACION" INT IDENTITY(1,1) CONSTRAINT "PK_INFORME_RELACIONES" PRIMARY KEY,
        "ID_INFORME" INT NOT NULL CONSTRAINT "FK_INFORME_RELACIONES_INFORME" REFERENCES "INFORMES" ("ID_INFORME"),
        "ID_INFORME_RELACIONADO" INT NOT NULL CONSTRAINT "FK_INFORME_RELACIONES_RELACIONADO" REFERENCES "INFORMES" ("ID_INFORME"),
        "TIPO" NVARCHAR(20) NOT NULL CONSTRAINT "DF_INFORME_RELACIONES_TIPO" DEFAULT 'RELACIONADO',
        "NOTA" NVARCHAR(500) NULL,
        CONSTRAINT "UQ_INFORME_RELACIONES" UNIQUE ("ID_INFORME", "ID_INFORME_RELACIONADO"),
        CONSTRAINT "CHK_INFORME_RELACIONES_TIPO" CHECK ("TIPO" IN ('RELACIONADO', 'SUPERA', 'ACLARA')),
        CONSTRAINT "CHK_INFORME_RELACIONES_DISTINTOS" CHECK ("ID_INFORME" <> "ID_INFORME_RELACIONADO")
    );
    CREATE INDEX "IX_INFORME_RELACIONES_RELACIONADO" ON "INFORME_RELACIONES" ("ID_INFORME_RELACIONADO");
END
GO

INSERT INTO "NORMAS" ("DENOMINACION", "TIPO", "NUMERO")
SELECT v."DENOMINACION", v."TIPO", v."NUMERO" FROM (VALUES
    (N'Constitución Política del Perú', N'Constitución', N'1993'),
    (N'TUO de la Ley N° 27444, Ley del Procedimiento Administrativo General (D.S. N° 004-2019-JUS)', N'Ley', N'27444'),
    (N'Ley N° 27867, Ley Orgánica de Gobiernos Regionales', N'Ley', N'27867'),
    (N'Ley N° 32069, Ley General de Contrataciones Públicas', N'Ley', N'32069'),
    (N'Ley N° 30057, Ley del Servicio Civil', N'Ley', N'30057'),
    (N'Decreto Legislativo N° 1440, del Sistema Nacional de Presupuesto Público', N'Decreto Legislativo', N'1440'),
    (N'TUO de la Ley N° 27806, Ley de Transparencia y Acceso a la Información Pública (D.S. N° 021-2019-JUS)', N'Ley', N'27806')
) AS v ("DENOMINACION", "TIPO", "NUMERO")
WHERE NOT EXISTS (SELECT 1 FROM "NORMAS" n WHERE n."DENOMINACION" = v."DENOMINACION");
GO
