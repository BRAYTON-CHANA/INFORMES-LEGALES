DELETE p FROM "INFORME_PERMISOS" p JOIN g ON g."ID_INFORME_PERMISO" = p."ID_INFORME_PERMISO" WHERE g."N" > 1;
GO

-- 2. Restricciones (se quitan si existen y se vuelven a crear: se puede correr más de una vez)
