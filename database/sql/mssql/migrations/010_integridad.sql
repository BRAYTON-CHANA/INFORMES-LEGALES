UPDATE p SET "PUEDE_EDITAR" = 1
FROM "INFORME_PERMISOS" p JOIN g ON g."ID_INFORME_PERMISO" = p."ID_INFORME_PERMISO"
WHERE g."N" = 1 AND g."EDITA" = 1 AND p."PUEDE_EDITAR" = 0;

;WITH g AS (
