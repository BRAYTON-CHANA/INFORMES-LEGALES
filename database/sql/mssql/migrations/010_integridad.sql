IF OBJECT_ID('CHK_INFORMES_ANIO', 'C') IS NOT NULL ALTER TABLE "INFORMES" DROP CONSTRAINT "CHK_INFORMES_ANIO";
ALTER TABLE "INFORMES" ADD CONSTRAINT "CHK_INFORMES_ANIO" CHECK ("ANIO" BETWEEN 1990 AND 2100);
IF OBJECT_ID('CHK_INFORMES_NO_SE_SUPERA', 'C') IS NOT NULL ALTER TABLE "INFORMES" DROP CONSTRAINT "CHK_INFORMES_NO_SE_SUPERA";
ALTER TABLE "INFORMES" ADD CONSTRAINT "CHK_INFORMES_NO_SE_SUPERA" CHECK ("ID_SUPERADO_POR" IS NULL OR "ID_SUPERADO_POR" <> "ID_INFORME");
IF OBJECT_ID('CHK_INFORMES_ANULADO', 'C') IS NOT NULL ALTER TABLE "INFORMES" DROP CONSTRAINT "CHK_INFORMES_ANULADO";
ALTER TABLE "INFORMES" ADD CONSTRAINT "CHK_INFORMES_ANULADO" CHECK ("ESTADO" <> 'ANULADO' OR "MOTIVO_ANULACION" IS NOT NULL);
IF OBJECT_ID('CHK_INFORMES_PUBLICADO', 'C') IS NOT NULL ALTER TABLE "INFORMES" DROP CONSTRAINT "CHK_INFORMES_PUBLICADO";
ALTER TABLE "INFORMES" ADD CONSTRAINT "CHK_INFORMES_PUBLICADO" CHECK ("PUBLICADO" = 0 OR "FECHA_PUBLICACION" IS NOT NULL);

IF OBJECT_ID('CHK_INFORME_ARCHIVOS_VERSION', 'C') IS NOT NULL ALTER TABLE "INFORME_ARCHIVOS" DROP CONSTRAINT "CHK_INFORME_ARCHIVOS_VERSION";
ALTER TABLE "INFORME_ARCHIVOS" ADD CONSTRAINT "CHK_INFORME_ARCHIVOS_VERSION" CHECK ("VERSION" > 0);
IF OBJECT_ID('CHK_INFORME_ARCHIVOS_TAMANIO', 'C') IS NOT NULL ALTER TABLE "INFORME_ARCHIVOS" DROP CONSTRAINT "CHK_INFORME_ARCHIVOS_TAMANIO";
ALTER TABLE "INFORME_ARCHIVOS" ADD CONSTRAINT "CHK_INFORME_ARCHIVOS_TAMANIO" CHECK ("TAMANIO" > 0);

IF OBJECT_ID('CHK_TIPOS_DOCUMENTO_USO', 'C') IS NOT NULL ALTER TABLE "TIPOS_DOCUMENTO" DROP CONSTRAINT "CHK_TIPOS_DOCUMENTO_USO";
ALTER TABLE "TIPOS_DOCUMENTO" ADD CONSTRAINT "CHK_TIPOS_DOCUMENTO_USO" CHECK ("USO_RESPUESTA" = 1 OR "USO_SOLICITUD" = 1);
IF OBJECT_ID('CHK_TIPOS_DOCUMENTO_ORDEN', 'C') IS NOT NULL ALTER TABLE "TIPOS_DOCUMENTO" DROP CONSTRAINT "CHK_TIPOS_DOCUMENTO_ORDEN";
ALTER TABLE "TIPOS_DOCUMENTO" ADD CONSTRAINT "CHK_TIPOS_DOCUMENTO_ORDEN" CHECK ("ORDEN" >= 0 AND "ORDEN_SOLICITUD" >= 0);

IF OBJECT_ID('CHK_INFORME_PERMISOS_DESTINO', 'C') IS NOT NULL ALTER TABLE "INFORME_PERMISOS" DROP CONSTRAINT "CHK_INFORME_PERMISOS_DESTINO";
ALTER TABLE "INFORME_PERMISOS" ADD CONSTRAINT "CHK_INFORME_PERMISOS_DESTINO" CHECK (
    (CASE WHEN "ID_USUARIO" IS NULL THEN 0 ELSE 1 END)
  + (CASE WHEN "ID_ROL" IS NULL THEN 0 ELSE 1 END)
  + (CASE WHEN "ID_UNIDAD_EJECUTORA" IS NULL THEN 0 ELSE 1 END) = 1);

-- Sin borrado en cascada: nada se borra (normas del AGN); un DELETE accidental debe fallar
