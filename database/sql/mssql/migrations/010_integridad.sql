-- 1. Corrección de datos
-- Superado por sí mismo o por un informe anulado → recalcular: queda superado por el SUPERA vigente más reciente, o vigente
UPDATE i SET "ID_SUPERADO_POR" = NULL, "VIGENCIA_CRITERIO" = 'VIGENTE'
FROM "INFORMES" i
WHERE i."ID_SUPERADO_POR" = i."ID_INFORME"
   OR EXISTS (SELECT 1 FROM "INFORMES" s WHERE s."ID_INFORME" = i."ID_SUPERADO_POR" AND s."ESTADO" = 'ANULADO');

UPDATE i SET "VIGENCIA_CRITERIO" = 'SUPERADO', "ID_SUPERADO_POR" = x."ID_INFORME"
FROM "INFORMES" i
JOIN (
    SELECT r."ID_INFORME_RELACIONADO" AS "B", MAX(r."ID_INFORME") AS "ID_INFORME"
    FROM "INFORME_RELACIONES" r JOIN "INFORMES" s ON s."ID_INFORME" = r."ID_INFORME"
    WHERE r."TIPO" = 'SUPERA' AND s."ESTADO" = 'VIGENTE' AND s."ACTIVO" = 1
    GROUP BY r."ID_INFORME_RELACIONADO"
) x ON x."B" = i."ID_INFORME"
WHERE i."ID_SUPERADO_POR" IS NULL AND i."VIGENCIA_CRITERIO" = 'VIGENTE' AND x."ID_INFORME" <> i."ID_INFORME";

-- Más de un archivo principal por informe y categoría → solo la versión mayor
UPDATE a SET "ES_PRINCIPAL" = 0
FROM "INFORME_ARCHIVOS" a
WHERE a."ES_PRINCIPAL" = 1 AND a."CATEGORIA" IN ('OFICIAL', 'SOLICITUD')
  AND a."VERSION" < (SELECT MAX(b."VERSION") FROM "INFORME_ARCHIVOS" b
                     WHERE b."ID_INFORME" = a."ID_INFORME" AND b."CATEGORIA" = a."CATEGORIA" AND b."ES_PRINCIPAL" = 1);

UPDATE "INFORMES" SET "MOTIVO_ANULACION" = N'Sin motivo registrado' WHERE "ESTADO" = 'ANULADO' AND "MOTIVO_ANULACION" IS NULL;
UPDATE "INFORMES" SET "FECHA_PUBLICACION" = "FECHA_CREACION" WHERE "PUBLICADO" = 1 AND "FECHA_PUBLICACION" IS NULL;
UPDATE "TIPOS_DOCUMENTO" SET "USO_RESPUESTA" = 1 WHERE "USO_RESPUESTA" = 0 AND "USO_SOLICITUD" = 0;

-- Más de una Sede Central → queda la de menor id
UPDATE "UNIDADES_EJECUTORAS" SET "ES_SEDE_CENTRAL" = 0
WHERE "ES_SEDE_CENTRAL" = 1
  AND "ID_UNIDAD_EJECUTORA" > (SELECT MIN("ID_UNIDAD_EJECUTORA") FROM "UNIDADES_EJECUTORAS" WHERE "ES_SEDE_CENTRAL" = 1);

-- Permisos con más de un destino → se conserva uno (usuario > rol > unidad ejecutora)
UPDATE "INFORME_PERMISOS" SET "ID_ROL" = NULL, "ID_UNIDAD_EJECUTORA" = NULL WHERE "ID_USUARIO" IS NOT NULL;
UPDATE "INFORME_PERMISOS" SET "ID_UNIDAD_EJECUTORA" = NULL WHERE "ID_ROL" IS NOT NULL;

-- Permisos repetidos (mismo informe y destino): queda el más antiguo con PUEDE_EDITAR si alguno lo tenía.
-- Es configuración de acceso, no documentación: dejar de compartir ya los elimina.
;WITH g AS (
    SELECT "ID_INFORME_PERMISO",
           MAX(CAST("PUEDE_EDITAR" AS INT)) OVER (PARTITION BY "ID_INFORME", "ID_USUARIO", "ID_ROL", "ID_UNIDAD_EJECUTORA") AS "EDITA",
           ROW_NUMBER() OVER (PARTITION BY "ID_INFORME", "ID_USUARIO", "ID_ROL", "ID_UNIDAD_EJECUTORA" ORDER BY "ID_INFORME_PERMISO") AS "N"
    FROM "INFORME_PERMISOS"
