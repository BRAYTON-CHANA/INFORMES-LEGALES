           ROW_NUMBER() OVER (PARTITION BY "ID_INFORME", "ID_USUARIO", "ID_ROL", "ID_UNIDAD_EJECUTORA" ORDER BY "ID_INFORME_PERMISO") AS "N"
    FROM "INFORME_PERMISOS"
