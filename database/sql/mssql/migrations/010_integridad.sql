    FOREIGN KEY ("ID_INFORME") REFERENCES "INFORMES" ("ID_INFORME");
IF OBJECT_ID('FK_INFORME_PERMISOS_INFORME', 'F') IS NOT NULL ALTER TABLE "INFORME_PERMISOS" DROP CONSTRAINT "FK_INFORME_PERMISOS_INFORME";
ALTER TABLE "INFORME_PERMISOS" ADD CONSTRAINT "FK_INFORME_PERMISOS_INFORME"
    FOREIGN KEY ("ID_INFORME") REFERENCES "INFORMES" ("ID_INFORME");
