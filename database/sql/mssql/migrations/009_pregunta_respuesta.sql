-- Tipos de documento: en qué lista aparece cada uno y en qué orden (1 = el más común)
IF COL_LENGTH('dbo.TIPOS_DOCUMENTO', 'USO_RESPUESTA') IS NULL
    ALTER TABLE "TIPOS_DOCUMENTO" ADD "USO_RESPUESTA" BIT NOT NULL CONSTRAINT "DF_TIPOS_DOCUMENTO_USO_RESPUESTA" DEFAULT 1;
IF COL_LENGTH('dbo.TIPOS_DOCUMENTO', 'USO_SOLICITUD') IS NULL
    ALTER TABLE "TIPOS_DOCUMENTO" ADD "USO_SOLICITUD" BIT NOT NULL CONSTRAINT "DF_TIPOS_DOCUMENTO_USO_SOLICITUD" DEFAULT 0;
IF COL_LENGTH('dbo.TIPOS_DOCUMENTO', 'ORDEN') IS NULL
    ALTER TABLE "TIPOS_DOCUMENTO" ADD "ORDEN" INT NOT NULL CONSTRAINT "DF_TIPOS_DOCUMENTO_ORDEN" DEFAULT 50;
IF COL_LENGTH('dbo.TIPOS_DOCUMENTO', 'ORDEN_SOLICITUD') IS NULL
    ALTER TABLE "TIPOS_DOCUMENTO" ADD "ORDEN_SOLICITUD" INT NOT NULL CONSTRAINT "DF_TIPOS_DOCUMENTO_ORDEN_SOLICITUD" DEFAULT 50;
GO

IF NOT EXISTS (SELECT 1 FROM "TIPOS_DOCUMENTO" WHERE "NOMBRE" = N'Solicitud')
    INSERT INTO "TIPOS_DOCUMENTO" ("NOMBRE", "PREFIJO") VALUES (N'Solicitud', N'SOLICITUD');

UPDATE t
SET "USO_RESPUESTA" = v."R", "USO_SOLICITUD" = v."S", "ORDEN" = v."O", "ORDEN_SOLICITUD" = v."OS"
FROM "TIPOS_DOCUMENTO" t
JOIN (VALUES
    (N'Informe Legal', 1, 0, 1, 50),
    (N'Opinión Legal', 1, 0, 2, 50),
    (N'Oficio', 1, 1, 3, 1),
    (N'Memorando', 1, 1, 4, 2),
    (N'Oficio Múltiple', 1, 1, 5, 5),
    (N'Memorando Múltiple', 1, 1, 6, 6),
    (N'Informe', 1, 1, 7, 4),
    (N'Proveído', 1, 1, 8, 3),
    (N'Carta', 1, 1, 9, 8),
    (N'Solicitud', 0, 1, 50, 7)
) AS v ("NOMBRE", "R", "S", "O", "OS") ON t."NOMBRE" = v."NOMBRE";
GO

-- Informes: datos de la pregunta
IF COL_LENGTH('dbo.INFORMES', 'ID_TIPO_SOLICITUD') IS NULL
    ALTER TABLE "INFORMES" ADD "ID_TIPO_SOLICITUD" INT NULL
        CONSTRAINT "FK_INFORMES_TIPO_SOLICITUD" REFERENCES "TIPOS_DOCUMENTO" ("ID_TIPO_DOCUMENTO");
IF COL_LENGTH('dbo.INFORMES', 'NUMERO_SOLICITUD') IS NULL
    ALTER TABLE "INFORMES" ADD "NUMERO_SOLICITUD" NVARCHAR(150) NULL;
IF COL_LENGTH('dbo.INFORMES', 'ID_UE_SOLICITANTE') IS NULL
    ALTER TABLE "INFORMES" ADD "ID_UE_SOLICITANTE" INT NULL
        CONSTRAINT "FK_INFORMES_UE_SOLICITANTE" REFERENCES "UNIDADES_EJECUTORAS" ("ID_UNIDAD_EJECUTORA");
GO

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'IX_INFORMES_UE_SOLICITANTE')
    CREATE INDEX "IX_INFORMES_UE_SOLICITANTE" ON "INFORMES" ("ID_UE_SOLICITANTE");

-- Archivos: nueva categoría SOLICITUD (PDF de la pregunta)
IF EXISTS (SELECT 1 FROM sys.check_constraints WHERE name = 'CHK_INFORME_ARCHIVOS_CATEGORIA')
    ALTER TABLE "INFORME_ARCHIVOS" DROP CONSTRAINT "CHK_INFORME_ARCHIVOS_CATEGORIA";
ALTER TABLE "INFORME_ARCHIVOS" ADD CONSTRAINT "CHK_INFORME_ARCHIVOS_CATEGORIA"
    CHECK ("CATEGORIA" IN ('OFICIAL', 'SOLICITUD', 'ANTECEDENTE'));
GO
