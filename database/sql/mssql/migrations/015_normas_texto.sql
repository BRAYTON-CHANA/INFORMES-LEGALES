-- ============================================
-- 015: la normativa del informe se guarda como texto (INFORME_NORMAS.NORMA), no como id.
-- El catálogo NORMAS queda solo como sugerencia al escribir; una norma que no está se
-- escribe a mano sin agregarla al catálogo (mismo cambio que tables/13).
-- ============================================
IF COL_LENGTH('dbo.INFORME_NORMAS', 'NORMA') IS NULL
    ALTER TABLE "INFORME_NORMAS" ADD "NORMA" NVARCHAR(500) NULL;
GO

IF COL_LENGTH('dbo.INFORME_NORMAS', 'ID_NORMA') IS NOT NULL
    EXEC sp_executesql N'UPDATE x SET "NORMA" = COALESCE(n."DENOMINACION", N''Norma '' + CAST(x."ID_NORMA" AS NVARCHAR(20)))
        FROM "INFORME_NORMAS" x LEFT JOIN "NORMAS" n ON n."ID_NORMA" = x."ID_NORMA" WHERE x."NORMA" IS NULL';
GO

ALTER TABLE "INFORME_NORMAS" ALTER COLUMN "NORMA" NVARCHAR(500) NOT NULL;
IF OBJECT_ID('UQ_INFORME_NORMAS', 'UQ') IS NOT NULL ALTER TABLE "INFORME_NORMAS" DROP CONSTRAINT "UQ_INFORME_NORMAS";
IF OBJECT_ID('FK_INFORME_NORMAS_NORMA', 'F') IS NOT NULL ALTER TABLE "INFORME_NORMAS" DROP CONSTRAINT "FK_INFORME_NORMAS_NORMA";
IF EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'IX_INFORME_NORMAS_NORMA' AND object_id = OBJECT_ID('dbo.INFORME_NORMAS'))
    DROP INDEX "IX_INFORME_NORMAS_NORMA" ON "INFORME_NORMAS";
GO

IF COL_LENGTH('dbo.INFORME_NORMAS', 'ID_NORMA') IS NOT NULL ALTER TABLE "INFORME_NORMAS" DROP COLUMN "ID_NORMA";
ALTER TABLE "INFORME_NORMAS" ADD CONSTRAINT "UQ_INFORME_NORMAS" UNIQUE ("ID_INFORME", "NORMA");
GO
