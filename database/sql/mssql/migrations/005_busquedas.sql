IF OBJECT_ID('dbo.INFORME_BUSQUEDAS', 'U') IS NULL
BEGIN
    CREATE TABLE "INFORME_BUSQUEDAS" (
        "ID_BUSQUEDA" INT IDENTITY(1,1) CONSTRAINT "PK_INFORME_BUSQUEDAS" PRIMARY KEY,
        "ID_USUARIO" INT NOT NULL CONSTRAINT "FK_INFORME_BUSQUEDAS_USUARIO" REFERENCES "USUARIOS" ("ID_USUARIO"),
        "ID_UNIDAD_EJECUTORA" INT NULL CONSTRAINT "FK_INFORME_BUSQUEDAS_UE" REFERENCES "UNIDADES_EJECUTORAS" ("ID_UNIDAD_EJECUTORA"),
        "TEXTO" NVARCHAR(200) NOT NULL,
        "RESULTADOS" INT NOT NULL,
        "FECHA" DATETIMEOFFSET NOT NULL CONSTRAINT "DF_INFORME_BUSQUEDAS_FECHA" DEFAULT SYSDATETIMEOFFSET()
    );
    CREATE INDEX "IX_INFORME_BUSQUEDAS_FECHA" ON "INFORME_BUSQUEDAS" ("FECHA");
END
GO
