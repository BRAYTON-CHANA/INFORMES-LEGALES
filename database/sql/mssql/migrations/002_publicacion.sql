-- ============================================
-- 002: publicación para las unidades ejecutoras y compartir por unidad ejecutora
-- (mismo cambio que tables/08_informes y 10_informe_permisos)
-- ============================================
IF COL_LENGTH('dbo.INFORMES', 'PUBLICADO') IS NULL
    ALTER TABLE "INFORMES" ADD "PUBLICADO" BIT NOT NULL CONSTRAINT "DF_INFORMES_PUBLICADO" DEFAULT 0;
IF COL_LENGTH('dbo.INFORMES', 'FECHA_PUBLICACION') IS NULL
    ALTER TABLE "INFORMES" ADD "FECHA_PUBLICACION" DATETIMEOFFSET NULL;
IF COL_LENGTH('dbo.INFORMES', 'ID_USUARIO_PUBLICA') IS NULL
    ALTER TABLE "INFORMES" ADD "ID_USUARIO_PUBLICA" INT NULL
        CONSTRAINT "FK_INFORMES_USUARIO_PUBLICA" REFERENCES "USUARIOS" ("ID_USUARIO");
IF COL_LENGTH('dbo.INFORME_PERMISOS', 'ID_UNIDAD_EJECUTORA') IS NULL
    ALTER TABLE "INFORME_PERMISOS" ADD "ID_UNIDAD_EJECUTORA" INT NULL
        CONSTRAINT "FK_INFORME_PERMISOS_UE" REFERENCES "UNIDADES_EJECUTORAS" ("ID_UNIDAD_EJECUTORA");
GO

IF EXISTS (SELECT 1 FROM sys.check_constraints WHERE name = 'CHK_INFORME_PERMISOS_DESTINO'
           AND definition NOT LIKE '%ID_UNIDAD_EJECUTORA%')
    ALTER TABLE "INFORME_PERMISOS" DROP CONSTRAINT "CHK_INFORME_PERMISOS_DESTINO";
GO

IF NOT EXISTS (SELECT 1 FROM sys.check_constraints WHERE name = 'CHK_INFORME_PERMISOS_DESTINO')
    ALTER TABLE "INFORME_PERMISOS" ADD CONSTRAINT "CHK_INFORME_PERMISOS_DESTINO"
        CHECK ("ID_USUARIO" IS NOT NULL OR "ID_ROL" IS NOT NULL OR "ID_UNIDAD_EJECUTORA" IS NOT NULL);
GO
